"""
=============================================================================
Small Hydropower Plant (SHP) Agentic RAG - Retrieval Grader State & Schemas
=============================================================================
Module: src.states.retrieval_grader_state
Purpose: Defines Pydantic validation models and LangGraph state schemas for
         the Reference-Free Retrieval Sufficiency Grader (Production CRAG).
         Evaluates whether synthesized context contains complete engineering
         data, formulas, and parameters to answer the user query and planned
         sub-queries without requiring external golden reference answers.
=============================================================================
"""

from typing import Any, TypedDict

from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# Pydantic Schema for Grader Output
# ---------------------------------------------------------------------------
class RetrievalGraderOutput(BaseModel):
    """Structured evaluation output generated by the Retrieval Sufficiency Grader."""

    is_sufficient: bool = Field(
        description="True if the retrieved context contains all necessary engineering data, formulas, "
        "and parameters to generate an accurate and complete answer; False if critical information is missing."
    )
    missing_aspects: list[str] = Field(
        default_factory=list,
        description="Specific engineering parameters, formulas, regulations, or data points missing from the context. "
        "Must be empty if is_sufficient is True.",
    )
    critique: str = Field(
        description="Concise technical evaluation explaining why the context is sufficient, or detailing the specific "
        "gaps and data deficits that prevent a complete answer.",
    )
    confidence_score: float = Field(
        default=1.0,
        ge=0.0,
        le=1.0,
        description="Confidence score (0.0 to 1.0) reflecting the certainty of the sufficiency evaluation.",
    )


# ---------------------------------------------------------------------------
# LangGraph State Schema
# ---------------------------------------------------------------------------
class RetrievalGraderState(TypedDict, total=False):
    """
    LangGraph state channel for Retrieval Grader execution.
    Operates as the pre-generation quality gate in the production LangGraph workflow.
    """

    # Inputs from prior nodes
    query: str                                             # Current active query
    user_query: str | None                                 # Compatible alias for original user query
    sub_queries: list[dict[str, Any]] | None               # SubQuery specs formulated by Planner
    synthesized_context: str | None                        # Structured context dossier from Synthesizer
    documents: list[dict[str, Any]] | None                 # Raw or balanced retrieved chunks
    cycle_count: int | None                                # Current loop iteration

    # Grader Outputs
    is_retrieval_sufficient: bool                          # Pre-generation gate decision
    missing_aspects: list[str]                             # Data points missing for Feedback Agent
    retrieval_critique: str                                # Diagnostic critique for Feedback Agent
    retrieval_confidence: float                            # Grader confidence score
    error: str | None                                      # Error message if grading encounters an exception


__all__ = [
    "RetrievalGraderOutput",
    "RetrievalGraderState",
]

