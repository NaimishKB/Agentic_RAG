import operator
from typing import Annotated, Any, Literal, TypedDict

from langchain_core.messages import BaseMessage
from langgraph.graph.message import add_messages


# ---------------------------------------------------------------------------
# Channel Reducers for Parallel Worker Scatter-Gather
# ---------------------------------------------------------------------------
def merge_sub_agent_results(
    left: dict[str, list[dict[str, Any]]] | None,
    right: dict[str, list[dict[str, Any]]] | None,
) -> dict[str, list[dict[str, Any]]]:
    """Reducer merging dictionary of sub-agent results keyed by sub_query_id."""
    merged: dict[str, list[dict[str, Any]]] = dict(left) if left else {}
    if not right:
        return merged
    for k, v in right.items():
        if k in merged:
            merged[k] = list(merged[k]) + list(v)
        else:
            merged[k] = list(v)
    return merged


# ---------------------------------------------------------------------------
# Core Data Models
# ---------------------------------------------------------------------------
class DocumentChunk(TypedDict, total=False):
    """Represents a single retrieved document chunk with rich citation metadata."""
    chunk_id: str                     # Unique deterministic chunk UUID/string
    content: str                      # Full markdown text of the chunk (with breadcrumbs)
    source_file: str                  # Source filename (e.g. HDP_AHN511.ppt)
    file_type: str                    # Document type (PDF, PPT, DOCX, XLS, TOOL_OUTPUT)
    page_or_slide: int | None         # Page number or slide index
    breadcrumb: str                   # Section path (e.g. Doc > Section > Table)
    is_table: bool                    # Flag indicating structured table data
    score: float                      # Cosine similarity score (or 1.0 for MCP tool output)


class SubQuery(TypedDict, total=False):
    """A decomposed sub-query planned for targeted retrieval."""
    sub_query_id: str                 # Identifier (e.g. "sq_1")
    query_text: str                   # Specific search query
    target_filter: dict[str, Any] | str | None # Qdrant filter (e.g. {"is_table": "true"}) or worker name
    rationale: str                    # Why this sub-query was formed


class FeedbackDiagnosis(TypedDict, total=False):
    """Structured diagnostic generated by Feedback Agent upon guardrail failure."""
    failure_type: Literal[
        "INSUFFICIENT_RETRIEVAL",      # Low context recall/sufficiency
        "HALLUCINATION_DETECTED",     # Answer contains ungrounded claims
        "OFF_TOPIC_ANSWER",           # Low answer relevancy
    ]
    missing_aspects: list[str]        # Specific engineering facts/tables missing
    critique: str                     # Human-readable explanation of the defect
    remediation_hint: str             # Actionable suggestion for the Planner Agent
    target_recommendations: list[str] # Recommended workers or filters


# ---------------------------------------------------------------------------
# Unified LangGraph State Schema
# ---------------------------------------------------------------------------
class AgentState(TypedDict, total=False):
    """
    Unified single-source-of-truth state channel for the SHP Agentic RAG system.
    All nodes across Planning, Orchestration, Synthesis, Grading, Generation,
    and Feedback read from and write to this state.
    """

    # ── Core Conversation & Input ──────────────────────────────────────
    messages: Annotated[list[BaseMessage], add_messages]  # Conversation history
    query: str                                             # Current active user query
    user_query: str | None                                 # Compatible alias
    original_query: str | None                             # Unmodified user input

    # ── Planner Decision & Intent ──────────────────────────────────────
    routing_decision: Literal[
        "rag_retrieval",              # Complex technical SHP question requiring RAG
        "direct_answer",              # Conversational greeting or simple factual question
        "out_of_scope",               # Non-SHP / disallowed domain query
    ] | None
    plan: list[str] | None                                 # High-level steps formulated by Planner
    sub_queries: list[dict[str, Any]] | None               # Decomposed SubQuery specs

    # ── Orchestration & Parallel Sub-Agent Retrieval ───────────────────
    tasks: list[dict[str, Any]] | None                     # Assigned worker tasks
    coordination_strategy: str | None                      # Strategy summary
    sub_agent_results: Annotated[                          # Results keyed by sub_query_id
        dict[str, list[dict[str, Any]]],
        merge_sub_agent_results
    ]
    all_retrieved_chunks: Annotated[                       # Flat chunk collection
        list[dict[str, Any]],
        operator.add
    ]
    total_retrieved: int | None                            # Count of unique retrieved chunks

    # ── Synthesis & Fusion ─────────────────────────────────────────────
    documents: list[dict[str, Any]] | None                 # Deduplicated, balanced RetrievedChunks
    synthesized_context: str | None                        # Clean context dossier assembled by Synthesizer
    executive_summary: str | None                          # High-level technical briefing
    conflicts_detected: list[str] | None                   # Contradictory parameters flagged
    citations: list[str] | None                            # Citations referenced
    coverage_score: float | None                           # Coverage score (0.0 to 1.0)

    # ── Retrieval Sufficiency Grader (Production CRAG) ─────────────────
    is_retrieval_sufficient: bool | None                   # True if context has sufficient data to answer
    missing_aspects: list[str] | None                      # Specific missing parameters if insufficient
    retrieval_critique: str | None                         # Reasoning explaining sufficiency decision
    retrieval_confidence: float | None                     # Grader confidence score (0.0 to 1.0)
    retrieval_metrics: dict[str, float] | None             # Offline benchmark metrics (if running evals)

    # ── Post-Generation Guardrail & Faithfulness ───────────────────────
    final_response: str | None                             # Answer text drafted by Generator
    generation_metrics: dict[str, float] | None            # {"faithfulness": 0.95}
    is_grounded: bool | None                               # True if post-gen faithfulness passes threshold
    unfaithful_statements: list[str] | None                # Hallucinated or unverified statements flagged
    guardrail_critique: str | None                         # Critique from DeepEval Guardrail

    # ── Feedback & Self-Correction Loop ────────────────────────────────
    feedback_diagnosis: dict[str, Any] | None              # Analysis fed back to Planner Agent
    cycle_count: int                                       # Number of full retry loops (max: 3)
    circuit_breaker_tripped: bool | None                   # True if circuit breaker halted retries

    # ── Error Channel ──────────────────────────────────────────────────
    error: str | None                                      # Error description if any node encounters failure


