"""
=============================================================================
Small Hydropower Plant (SHP) Agentic RAG - Synthesizer Agent State & Schemas
=============================================================================
Module: src.states.synthesizeragent_state
Purpose: Defines Pydantic output validation models and LangGraph state schemas
         for the Synthesizer Agent. Handles multi-source chunk fusion,
         deduplication, citation tracking, and conflict detection.
=============================================================================
"""

from typing import Any, TypedDict

from pydantic import BaseModel, Field

from src.states.orchestratoragent_state import RetrievedChunk


# ---------------------------------------------------------------------------
# Pydantic Schemas for Structured Output
# ---------------------------------------------------------------------------
class SynthesizerOutput(BaseModel):
    """Structured output generated by the Synthesizer Agent."""
    executive_summary: str = Field(
        description="High-level engineering briefing synthesizing key findings across all sub-queries"
    )
    synthesized_context: str = Field(
        description="Clean, structured evidence dossier with precise citation tags for each technical fact"
    )
    conflicts_detected: list[str] = Field(
        default_factory=list,
        description="List of detected technical discrepancies, differing values, or conflicting specifications across sources"
    )
    citations_used: list[str] = Field(
        default_factory=list,
        description="List of distinct source document references cited in the synthesized context"
    )
    coverage_score: float = Field(
        default=1.0,
        ge=0.0,
        le=1.0,
        description="Estimated fractional coverage (0.0 to 1.0) of all technical facets required by the sub-queries"
    )


# ---------------------------------------------------------------------------
# LangGraph State Schema
# ---------------------------------------------------------------------------
class SynthesizerAgentState(TypedDict, total=False):
    """
    LangGraph state channel for Synthesizer Agent execution.
    Can operate standalone or as part of the overarching multi-agent AgentState.
    """
    # Inputs
    query: str                                             # Current active query
    user_query: str | None                                 # Compatible alias for original user query
    sub_queries: list[dict[str, Any]] | None               # SubQuery specs formulated by Planner
    sub_agent_results: dict[str, list[dict[str, Any]]] | None # Chunks grouped by sub_query_id
    all_retrieved_chunks: list[dict[str, Any]] | None      # Flat list of raw chunks from all workers

    # Outputs
    documents: list[dict[str, Any]] | None                 # Deduplicated, balanced, and ranked RetrievedChunks
    synthesized_context: str | None                        # Structured evidence dossier for downstream Guardrail & Generator
    executive_summary: str | None                          # Concise technical briefing
    conflicts_detected: list[str] | None                   # Contradictory figures or specifications detected
    citations: list[str] | None                            # Citations referenced
    coverage_score: float | None                           # Coverage score (0.0 to 1.0)
    error: str | None                                      # Error description if synthesis fails


__all__ = [
    "RetrievedChunk",
    "SynthesizerAgentState",
    "SynthesizerOutput",
]

